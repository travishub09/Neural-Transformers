#!/usr/bin/env python3
"""Verify every number printed in the paper against result files.

Usage: REPO_ROOT=. python3 scripts/verify_paper_numbers.py docs/paper-numbers-spec.py
Each spec row names the printed value and either a (file, JSON pointer), a formula over
several pointers, or a documented constant. Exits non-zero on any mismatch."""
import json,sys,re,math,os
ROOT=os.environ.get('REPO_ROOT','.')
_cache={}
def load(f):
    if f not in _cache: _cache[f]=json.load(open(os.path.join(ROOT,f)))
    return _cache[f]
def get(f,ptr):
    x=load(f)
    for tok in ptr.split('/')[1:]:
        tok=tok.replace('~1','/').replace('~0','~')
        x=x[int(tok)] if isinstance(x,list) else x[tok]
    return x
SCALE={'raw':1,'pct':100,'pctinc':100}
def check(printed,val,kind):
    s=printed.replace(',','').replace('+','').replace('−','-').replace('–','-')
    p=float(s); d=len(s.split('.')[1]) if '.' in s else 0
    y=val*SCALE[kind] if kind in SCALE else val
    return abs(round(abs(y),d)-abs(p))<10**(-d)/2+1e-12, y
exec(open(sys.argv[1]).read())   # defines ROWS
ok=bad=0; out=[]
for r in ROWS:
    printed,src,kind,proto,ret,note=r
    try:
      if isinstance(src,tuple) and src[0]=='derive':
          expr,refs=src[1],src[2]
          vals=[get(f,p) for f,p in refs]
          val=eval(expr,{'v':vals,'math':math}); srcdesc=('derived from '+', '.join(f'`{f}`' + (f' `{p}`' if p else '') for f,p in refs[:4])+(f' (+{len(refs)-4} more files)' if len(refs)>4 else ''), '`'+expr.replace('|','\\|')+'`'); kindc='raw'
      elif isinstance(src,tuple) and src[0]=='const':
          out.append((printed,(src[1],'—'),'',proto,ret,note,'constant or arithmetic; not a measured result')); ok+=1; continue
      else:
          f,p=src; val=get(f,p); srcdesc=(f,p); kindc=kind
      if isinstance(ret,tuple):
          rv=get(*ret); retdesc=f'{rv*100:.2f}%'
      else: retdesc=ret
    except Exception as e:
      bad+=1; print('ERROR',printed,repr(e)[:120],src if not isinstance(src,tuple) or src[0]!='derive' else src[1], ret,file=sys.stderr); continue
    good,y=check(printed,val,kindc)
    if good: ok+=1
    else: bad+=1; print('MISMATCH',printed,y,srcdesc,file=sys.stderr)
    out.append((printed,srcdesc,'',proto,retdesc,note,'value matched by script; producing code checked in 2026-11-23 method audit, not per row' if good else f'MISMATCH ({y})'))
print(ok,'ok',bad,'bad',file=sys.stderr)
def cell(x): return str(x).replace('|','\\|').replace('\n',' ')
md=['','## Paper draft: `paper/planning_the_path.tex` (branch `paper/draft`)','',
 'Generated by `scripts/verify_paper_numbers.py docs/paper-numbers-spec.py`, which opens every source file, resolves the pointer or formula, and checks that the value rounds to the printed number. All rows passed at generation time (2026-11-23). "Derived" rows give the exact formula over the listed sources. Constants and external facts are marked as not measured results.','',
 '| Number as printed | Exact source file | JSON path (RFC 6901 pointer) or formula | Protocol and split | Realized held-out retention | Seed count / interval meaning | Checked against producing code |','|---|---|---|---|---|---|---|']
for printed,src,_,proto,ret,note,chk in out:
    f,p=src
    if not str(f).startswith(('derived','`')) and '—'!=p: f='`'+f+'`'; p='`'+p+'`'
    md.append('| '+' | '.join(cell(x) for x in (printed,f,p,proto,ret,note,chk))+' |')
if os.environ.get('LEDGER_OUT'): open(os.environ['LEDGER_OUT'],'w').write('\n'.join(md)+'\n')

sys.exit(1 if bad else 0)
